function getSavedLanguage() {
  const savedLanguage = localStorage.getItem('siteLanguage');

  if (savedLanguage === 'en' || savedLanguage === 'id') {
    return savedLanguage;
  }

  return 'id';
}


function applyTranslations(language) {
  const lang = translations[language] ? language : 'id';
  const currentTranslations = translations[lang];

  // Update normal text
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');

    if (
      Object.prototype.hasOwnProperty.call(
        currentTranslations,
        key
      )
    ) {
      element.textContent = currentTranslations[key];
    }
  });

  // Update meta content
  document.querySelectorAll('[data-i18n-content]').forEach((element) => {
    const key = element.getAttribute('data-i18n-content');

    if (
      Object.prototype.hasOwnProperty.call(
        currentTranslations,
        key
      )
    ) {
      element.setAttribute(
        'content',
        currentTranslations[key]
      );
    }
  });

  // Update placeholder
  document
    .querySelectorAll('[data-i18n-placeholder]')
    .forEach((element) => {
      const key = element.getAttribute(
        'data-i18n-placeholder'
      );

      if (
        Object.prototype.hasOwnProperty.call(
          currentTranslations,
          key
        )
      ) {
        element.setAttribute(
          'placeholder',
          currentTranslations[key]
        );
      }
    });

  // Update alt text
  document
    .querySelectorAll('[data-i18n-alt]')
    .forEach((element) => {
      const key = element.getAttribute('data-i18n-alt');

      if (
        Object.prototype.hasOwnProperty.call(
          currentTranslations,
          key
        )
      ) {
        element.setAttribute(
          'alt',
          currentTranslations[key]
        );
      }
    });

  // Update aria-label
  document
    .querySelectorAll('[data-i18n-aria]')
    .forEach((element) => {
      const key = element.getAttribute('data-i18n-aria');

      if (
        Object.prototype.hasOwnProperty.call(
          currentTranslations,
          key
        )
      ) {
        element.setAttribute(
          'aria-label',
          currentTranslations[key]
        );
      }
    });

  // Update document language
  document.documentElement.lang = lang;

  // Update page title only when the page explicitly uses data-i18n
  const titleElement = document.querySelector(
    'title[data-i18n]'
  );

  if (titleElement) {
    const titleKey = titleElement.getAttribute('data-i18n');

    if (
      Object.prototype.hasOwnProperty.call(
        currentTranslations,
        titleKey
      )
    ) {
      document.title = currentTranslations[titleKey];
    }
  }

  // Update language buttons
  document
    .querySelectorAll('[data-language], [data-lang]')
    .forEach((button) => {
      const buttonLanguage =
        button.getAttribute('data-language') ||
        button.getAttribute('data-lang');

      const isActive = buttonLanguage === lang;

      button.classList.toggle(
        'active',
        isActive
      );

      button.setAttribute(
        'aria-pressed',
        isActive ? 'true' : 'false'
      );
    });

  // Save selected language
  localStorage.setItem(
    'siteLanguage',
    lang
  );
}


function setupLanguageSwitcher() {
  document
    .querySelectorAll('[data-language], [data-lang]')
    .forEach((button) => {
      button.addEventListener('click', () => {
        const language =
          button.getAttribute('data-language') ||
          button.getAttribute('data-lang');

        if (
          language === 'id' ||
          language === 'en'
        ) {
          applyTranslations(language);
        }
      });
    });
}


function initializeLanguage() {
  const language = getSavedLanguage();

  applyTranslations(language);
  setupLanguageSwitcher();
}


if (document.readyState === 'loading') {
  document.addEventListener(
    'DOMContentLoaded',
    initializeLanguage
  );
} else {
  initializeLanguage();
}